import { afterAll, describe, expect, it } from 'vitest'
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { discoverClaudeCodeSessions } from '../src/dialects/claude-code/sessions/discover.js'
import { readClaudeSession } from '../src/dialects/claude-code/sessions/parse.js'

const root = mkdtempSync(join(tmpdir(), 'hf-claude-title-'))
afterAll(() => { rmSync(root, { recursive: true, force: true }) })

let line = 0
function user(sessionId: string, content: unknown, extra: Record<string, unknown> = {}): Record<string, unknown> {
  line += 1
  return { type: 'user', uuid: `u${String(line)}`, parentUuid: line === 1 ? null : `a${String(line - 1)}`, sessionId, cwd: '/w', timestamp: '2026-01-01T00:00:00.000Z', message: { role: 'user', content }, ...extra }
}
function assistant(sessionId: string): Record<string, unknown> {
  return { type: 'assistant', uuid: `a${String(line)}`, parentUuid: `u${String(line)}`, sessionId, cwd: '/w', timestamp: '2026-01-01T00:00:01.000Z', message: { role: 'assistant', content: [{ type: 'text', text: 'ok' }] } }
}

/** A transcript whose first messages are what Claude Code puts there itself, then the person's question. */
function transcript(sessionId: string, ...extra: Record<string, unknown>[]): string {
  line = 0
  const records = [
    { type: 'queue-operation', operation: 'enqueue', sessionId },
    user(sessionId, 'Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages.', { isMeta: true }),
    user(sessionId, '<command-name>/model</command-name>\n<command-message>model</command-message>\n<command-args></command-args>'),
    user(sessionId, '<local-command-stdout>Set model to opus</local-command-stdout>'),
    user(sessionId, [{ type: 'text', text: '<system-reminder>\nThe user opened a file\n</system-reminder>' }, { type: 'text', text: '  Why does the\n  build fail on Windows?  ' }]),
    assistant(sessionId),
    user(sessionId, 'second question'),
    assistant(sessionId),
    ...extra,
  ]
  const file = join(root, `${sessionId}.jsonl`)
  writeFileSync(file, records.map(record => JSON.stringify(record)).join('\n') + '\n')
  return file
}

async function listed(file: string): Promise<string | undefined> {
  for await (const item of discoverClaudeCodeSessions(file)) return item.title
  return undefined
}

async function imported(file: string): Promise<string | undefined> {
  return (await readClaudeSession({ ref: file, sourceId: file })).session.title
}

describe('Claude Code session titles', () => {
  it('falls back to the first message the person typed, on one line, skipping meta, commands and reminders', async () => {
    const file = transcript('11111111-0000-4000-8000-000000000001')
    expect(await listed(file)).toBe('Why does the build fail on Windows?')
    expect(await imported(file)).toBe('Why does the build fail on Windows?')
  })

  it('prefers a /rename title (the last one), then the first AI title, then the latest summary', async () => {
    const sid = '11111111-0000-4000-8000-000000000002'
    const renamed = transcript(sid,
      { type: 'ai-title', sessionId: sid, aiTitle: 'Fix Windows build' },
      { type: 'custom-title', sessionId: sid, customTitle: 'first name' },
      { type: 'ai-title', sessionId: sid, aiTitle: 'worktree-abc' },
      { type: 'custom-title', sessionId: sid, customTitle: 'Windows build  fix' })
    expect(await listed(renamed)).toBe('Windows build fix')
    expect(await imported(renamed)).toBe('Windows build fix')

    const ai = transcript('11111111-0000-4000-8000-000000000003',
      { type: 'ai-title', aiTitle: 'Fix Windows build' }, { type: 'ai-title', aiTitle: 'worktree-abc' })
    expect(await listed(ai)).toBe('Fix Windows build')
    expect(await imported(ai)).toBe('Fix Windows build')

    const summarized = transcript('11111111-0000-4000-8000-000000000004',
      { type: 'summary', summary: 'Old summary', leafUuid: 'a2' }, { type: 'summary', summary: 'Windows build investigation', leafUuid: 'a7' })
    expect(await listed(summarized)).toBe('Windows build investigation')
    expect(await imported(summarized)).toBe('Windows build investigation')
  })

  it('finds a /rename appended to the end of a long transcript', async () => {
    const sid = '11111111-0000-4000-8000-000000000005'
    const filler = Array.from({ length: 400 }, () => ({ type: 'progress', sessionId: sid, data: 'x'.repeat(1024) }))
    const file = transcript(sid, ...filler, { type: 'custom-title', sessionId: sid, customTitle: 'Renamed late' })
    expect(await listed(file)).toBe('Renamed late')
  })
})
