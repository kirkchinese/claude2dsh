/**
 * A Claude Code session's title, chosen the way Claude Code shows it: the
 * name given with `/rename` (a `custom-title` record, the last one wins), else
 * the generated title (the first `ai-title` record; later ones are rewritten
 * per turn), else the latest `summary` record (older transcripts), else the
 * person's first real message.
 */
import type { RawRecord } from './types.js'

/** Longest title kept for a first message; the rest of a long paste is not a title. */
const PROMPT_TITLE_CHARS = 200

/**
 * What Claude Code writes as a user message that the person did not type:
 * slash-command wrappers and their output, system reminders, IDE and
 * environment blocks. Such a message is never the title.
 */
const INJECTED_PREFIXES = [
  '<command-name>', '<command-message>', '<command-args>', '<local-command-caveat>', '<local-command-stdout>', '<local-command-stderr>',
  '<system-reminder>', '<environment_context>', '<user_instructions>', '<ide_opened_file>', '<ide_selection>', '<ide_diagnostics>',
  '<bash-input>', '<bash-stdout>', '<bash-stderr>', 'Caveat: The messages below were generated by the user while running local commands',
  '[Request interrupted by user',
]

/** Text on one line, whitespace collapsed; `undefined` when nothing is left. */
export function oneLine(text: string, max = Number.POSITIVE_INFINITY): string | undefined {
  const line = text.trim().replace(/\s+/gu, ' ')
  if (line.length === 0) return undefined
  return line.length <= max ? line : `${line.slice(0, max - 1).trimEnd()}…`
}

function nonEmpty(value: unknown): string | undefined {
  return typeof value === 'string' ? oneLine(value) : undefined
}

/** Whether a user message's text is something Claude Code or the IDE put there rather than the person. */
export function isInjectedPrompt(text: string): boolean {
  const trimmed = text.trimStart()
  return trimmed.length === 0 || INJECTED_PREFIXES.some(prefix => trimmed.startsWith(prefix))
}

/** The text the person typed in a user record, or `undefined` for anything else (tool results, meta, wrappers). */
export function typedPrompt(record: RawRecord): string | undefined {
  if (record.type !== 'user' || record.isMeta === true || (record as { isCompactSummary?: unknown }).isCompactSummary === true) return undefined
  const content = record.message?.content
  const parts: string[] = []
  if (typeof content === 'string') parts.push(content)
  else if (Array.isArray(content)) {
    for (const block of content as unknown[]) {
      if (typeof block === 'string') parts.push(block)
      else if (typeof block === 'object' && block !== null && (block as { type?: unknown }).type === 'text' && typeof (block as { text?: unknown }).text === 'string') {
        parts.push((block as { text: string }).text)
      }
    }
  }
  // A message's own blocks can mix an IDE note with what was typed: the first block that is not injected is the prompt.
  for (const part of parts) if (!isInjectedPrompt(part)) return part
  return undefined
}

/** Collects the title carriers of one transcript, record by record, in file order. */
export class ClaudeTitle {
  private custom: string | undefined
  private ai: string | undefined
  private summary: string | undefined
  private prompt: string | undefined

  observe(record: RawRecord): void {
    if (record.type === 'custom-title') this.custom = nonEmpty((record as { customTitle?: unknown }).customTitle) ?? this.custom
    else if (record.type === 'ai-title') this.ai ??= nonEmpty(record.aiTitle)
    else if (record.type === 'summary') this.summary = nonEmpty(record.summary) ?? nonEmpty(record.title) ?? this.summary
    else if (this.prompt === undefined) {
      const typed = typedPrompt(record)
      if (typed !== undefined) this.prompt = oneLine(typed, PROMPT_TITLE_CHARS)
    }
  }

  get title(): string | undefined {
    return this.custom ?? this.ai ?? this.summary ?? this.prompt
  }
}
